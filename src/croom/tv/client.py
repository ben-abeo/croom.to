"""
The seam to the TV: the part of aiowebostv's WebOsClient the TV service uses, and the factory for the real one.
The service only ever sees a TvClient it was handed, so its tests run on a fake and never touch a TV or the library.
"""

from typing import Any, Awaitable, Callable, Dict, List, Optional, Protocol

from croom.tv.errors import TvError

StateCallback = Callable[[Any], Awaitable[None]]


class TvClient(Protocol):
    """What the service uses of aiowebostv.WebOsClient (names and signatures as the library has them; call them
    positionally). tv_info and tv_state are the library's WebOsTvInfo and WebOsTvState."""

    client_key: Optional[str]
    tv_info: Any
    tv_state: Any

    async def connect(self) -> bool: ...
    async def disconnect(self) -> None: ...
    def is_connected(self) -> bool: ...
    async def register_state_update_callback(self, callback: StateCallback) -> None: ...

    async def power_off(self) -> None: ...
    async def power_on(self) -> Dict[str, Any]: ...
    async def volume_up(self) -> Dict[str, Any]: ...
    async def volume_down(self) -> Dict[str, Any]: ...
    async def set_volume(self, volume: int) -> Dict[str, Any]: ...
    async def set_mute(self, mute: bool) -> Dict[str, Any]: ...
    async def channel_up(self) -> Dict[str, Any]: ...
    async def channel_down(self) -> Dict[str, Any]: ...
    async def set_channel(self, channel: str) -> Dict[str, Any]: ...
    async def get_inputs(self) -> Optional[List[Dict[str, Any]]]: ...
    async def set_input(self, input_id: str) -> Dict[str, Any]: ...
    async def get_apps(self) -> Optional[List[Dict[str, Any]]]: ...
    async def launch_app(self, app: str) -> Dict[str, Any]: ...
    async def send_message(self, message: str) -> Dict[str, Any]: ...

    # The remote's keys and the cursor, over the library's pointer socket
    async def button(self, name: str) -> None: ...
    async def move(self, d_x: int, d_y: int, down: int = 0) -> None: ...
    async def click(self) -> None: ...
    async def scroll(self, d_x: int, d_y: int) -> None: ...

    # Reads of the TV's state
    async def get_volume(self) -> Optional[int]: ...
    async def get_muted(self) -> Optional[bool]: ...
    async def get_input(self) -> Optional[str]: ...
    async def get_current_app(self) -> Optional[str]: ...
    async def get_current_channel(self) -> Dict[str, Any]: ...
    async def get_power_state(self) -> Dict[str, Any]: ...


ClientFactory = Callable[[str, Optional[str]], TvClient]


def real_client_factory(host: str, key: Optional[str]) -> TvClient:
    """A client for the real TV at host, paired with key (None to pair). Call it from a running event loop: the
    library binds to the loop it is created in. The library is imported here, not at the top of the module, so a
    room without a TV runs without it."""
    try:
        from aiowebostv import WebOsClient
    except ImportError as e:
        raise TvError("The TV library is not installed on this device: pip install aiowebostv") from e
    return WebOsClient(host, key)
